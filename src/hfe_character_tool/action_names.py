_FAMILY_ACTIONS = {key: actions for key, _label, actions in FAMILIES}
_FAMILY_LABELS = {key: label for key, label, _actions in FAMILIES}
# A move set needs this many family-specific names before it is recognised.
MIN_FAMILY_MATCHES = 3


def _normalise(name: str) -> str:
    return name.strip().lstrip("\\").strip().lower()


def action_parts(action_name: str) -> tuple[str, ...]:
    """SPT action entries can alias several names: "attack1, attack3" or "a / b"."""
    parts = (_normalise(part) for part in re.split(r"[,/]", action_name))
    return tuple(part for part in parts if part)


def infer_family(action_names: Iterable[str]) -> str | None:
    names = {part for name in action_names for part in action_parts(name)}
    best: str | None = None
    best_score = MIN_FAMILY_MATCHES - 1
    for key, _label, actions in FAMILIES:
        score = sum(1 for name in actions if name in names and name not in GENERIC)
        if score > best_score:
            best, best_score = key, score
    return best


def family_label(family: str | None) -> str:
    return _FAMILY_LABELS.get(family or "", "")


def _describe_part(part: str, family: str | None) -> str:
    if part.startswith("_old_"):
        rest = part[len("_old_") :]
        old = _describe_part(rest, family) or _describe_part(f"_{rest}", family)
        return f"{old}（旧版）" if old else ""
    specific = _FAMILY_ACTIONS.get(family or "", {})
    if part in specific:
        return specific[part]
    if part in GENERIC:
        return GENERIC[part]
    for pattern, template in _GENERIC_PATTERNS:
        match = pattern.fullmatch(part)
        if match:
            return template.format(*match.groups())
    return ""


def describe_action(action_name: str, family: str | None) -> str:
    """Chinese name for an SPT action, or "" when the reference does not cover it."""
    seen: list[str] = []
    for part in action_parts(action_name):
        text = _describe_part(part, family)
        if text and text not in seen:
            seen.append(text)
    return " / ".join(seen)
